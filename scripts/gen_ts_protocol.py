"""
Generate TypeScript protocol types from the Pydantic models.

    uv run python scripts/gen_ts_protocol.py          # write
    uv run python scripts/gen_ts_protocol.py --check  # CI: fail if stale

Emits payload interfaces, the enums as string-literal unions, a
``MessageMap`` from PAYLOAD_REGISTRY so the web client's envelope is a
discriminated union checked by the compiler, and ``PAYLOAD_FIELDS`` so
incoming messages are validated at runtime against the same models
(docs/decisions.md D36).
"""

from __future__ import annotations

import sys
from enum import StrEnum
from pathlib import Path
from typing import Any

from packages.protocol.codec import PAYLOAD_REGISTRY
from packages.protocol.constants import PROTOCOL_VERSION
from packages.protocol.enums import Capability, MessageType

OUT = Path(__file__).resolve().parent.parent / "apps/web/src/lib/protocol.gen.ts"

_SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}


def _split_nullable(schema: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """``X | None`` arrives as anyOf [X, null]: return (X, True)."""
    variants = schema.get("anyOf")
    if variants is None:
        return schema, False
    rest = [v for v in variants if v.get("type") != "null"]
    if len(rest) != 1 or len(rest) == len(variants):
        raise ValueError(f"unsupported union: {schema}")
    return rest[0], True


def _field_kind(schema: dict[str, Any]) -> str:
    """Runtime check kind for a field, as understood by protocol.ts."""
    if "$ref" in schema:
        return "string"  # every $ref here is a str enum
    if schema.get("type") == "array":
        return f"{_field_kind(schema['items'])}[]"
    return str(schema["type"])


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"].rsplit("/", 1)[-1])
    if schema.get("type") == "array":
        return f"{_ts_type(schema['items'])}[]"
    if schema.get("type") in _SCALARS:
        return _SCALARS[schema["type"]]
    raise ValueError(f"unsupported schema: {schema}")


def _enum(cls: type[StrEnum]) -> str:
    members = " | ".join(f'"{m.value}"' for m in cls)
    return f"export type {cls.__name__} = {members};\n"


def generate() -> str:
    out = [
        "// Generated by scripts/gen_ts_protocol.py from packages/protocol. Do not edit.\n\n",
        f"export const PROTOCOL_VERSION = {PROTOCOL_VERSION};\n\n",
        _enum(MessageType),
        "\n",
        _enum(Capability),
    ]

    for model in dict.fromkeys(PAYLOAD_REGISTRY.values()):
        schema = model.model_json_schema()
        required = set(schema.get("required", []))
        summary = " ".join((model.__doc__ or "").strip().split("\n\n")[0].split())
        out.append(f"\n/** {summary} */\n")
        out.append(f"export interface {model.__name__} {{\n")
        for name, prop in schema["properties"].items():
            optional = "" if name in required else "?"
            inner, nullable = _split_nullable(prop)
            ts = _ts_type(inner) + (" | null" if nullable else "")
            out.append(f"  {name}{optional}: {ts};\n")
        out.append("}\n")

    out.append("\nexport interface MessageMap {\n")
    for msg_type, model in PAYLOAD_REGISTRY.items():
        out.append(f"  {msg_type.value}: {model.__name__};\n")
    out.append("}\n")

    out.append(
        "\nexport type FieldKind = "
        '"string" | "integer" | "number" | "boolean" | "string[]";\n'
        "export interface FieldSpec {\n  kind: FieldKind;\n  optional: boolean;\n"
        "  nullable: boolean;\n}\n"
        "\nexport const PAYLOAD_FIELDS: Record<MessageType, Record<string, FieldSpec>> = {\n"
    )
    for msg_type, model in PAYLOAD_REGISTRY.items():
        schema = model.model_json_schema()
        required = set(schema.get("required", []))
        out.append(f"  {msg_type.value}: {{\n")
        for name, prop in schema["properties"].items():
            optional = "false" if name in required else "true"
            inner, nullable = _split_nullable(prop)
            out.append(
                f'    {name}: {{ kind: "{_field_kind(inner)}", optional: {optional}, '
                f"nullable: {str(nullable).lower()} }},\n"
            )
        out.append("  },\n")
    out.append("};\n")
    return "".join(out)


if __name__ == "__main__":
    content = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != content:
            sys.exit(f"{OUT} is stale: run `uv run python scripts/gen_ts_protocol.py`")
        print("protocol.gen.ts is up to date")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(content)
        print(f"wrote {OUT}")
